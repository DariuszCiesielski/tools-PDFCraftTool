// Node >=22 exposes an experimental global `localStorage` (Web Storage API) that shadows
// jsdom's implementation and lacks clear()/getItem(). Replace it with an in-memory Storage.
class MemoryStorage implements Storage {
  private store = new Map<string, string>();
  get length() { return this.store.size; }
  clear() { this.store.clear(); }
  getItem(key: string) { return this.store.has(key) ? this.store.get(key)! : null; }
  key(index: number) { return Array.from(this.store.keys())[index] ?? null; }
  removeItem(key: string) { this.store.delete(key); }
  setItem(key: string, value: string) { this.store.set(key, String(value)); }
}
for (const target of [globalThis, window]) {
  Object.defineProperty(target, 'localStorage', { value: new MemoryStorage(), writable: true, configurable: true });
}
